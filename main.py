from parking_manager import ParkingManager


def main():

    print("===================================")
    print("      PARKING MANAGEMENT SYSTEM")
    print("===================================")

    try:
        rows = int(input("Брой редове на паркинга: "))
        cols = int(input("Брой колони на паркинга: "))

    except ValueError:
        print("Невалиден размер.")
        return

    if rows <= 0 or cols <= 0:
        print("Размерите трябва да са положителни.")
        return

    manager = ParkingManager(rows, cols)

    while True:

        print("\n========== MENU ==========")
        print("1. Покажи паркинга")
        print("2. Добави автомобил")
        print("3. Премахни автомобил")
        print("4. Покажи автомобилите")
        print("5. Покажи чакащите автомобили")
        print("6. Търси автомобил")
        print("7. Undo последното действие")
        print("8. Покажи историята")
        print("9. Статистика")
        print("10. Изход")

        choice = input("\nИзбор: ").strip()

        # -------------------------------------------------
        # 1. PARKING
        # -------------------------------------------------

        if choice == "1":

            manager.parking.display()

        # -------------------------------------------------
        # 2. ADD CAR
        # -------------------------------------------------

        elif choice == "2":

            plate = input(
                "Регистрационен номер: "
            ).strip().upper()

            brand = input(
                "Марка: "
            ).strip()

            model = input(
                "Модел: "
            ).strip()

            if not plate or not brand or not model:
                print("Всички полета са задължителни.")
                continue

            manager.add_car(
                plate,
                brand,
                model
            )

        # -------------------------------------------------
        # 3. REMOVE CAR
        # -------------------------------------------------

        elif choice == "3":

            plate = input(
                "Регистрационен номер за премахване: "
            ).strip().upper()

            manager.remove_car(plate)

        # -------------------------------------------------
        # 4. SHOW CARS
        # -------------------------------------------------

        elif choice == "4":

            manager.show_cars()

        # -------------------------------------------------
        # 5. SHOW QUEUE
        # -------------------------------------------------

        elif choice == "5":

            manager.show_queue()

        # -------------------------------------------------
        # 6. SEARCH
        # -------------------------------------------------

        elif choice == "6":

            plate = input(
                "Регистрационен номер за търсене: "
            ).strip().upper()

            manager.search_car(plate)

        # -------------------------------------------------
        # 7. UNDO
        # -------------------------------------------------

        elif choice == "7":

            manager.undo()

        # -------------------------------------------------
        # 8. HISTORY
        # -------------------------------------------------

        elif choice == "8":

            manager.show_history()

        # -------------------------------------------------
        # 9. STATISTICS
        # -------------------------------------------------

        elif choice == "9":

            manager.statistics()

        # -------------------------------------------------
        # 10. EXIT
        # -------------------------------------------------

        elif choice == "10":

            print("Програмата приключи.")
            break

        else:

            print("Невалиден избор.")


if __name__ == "__main__":
    main()